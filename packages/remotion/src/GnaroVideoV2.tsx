import React from 'react';
import { AbsoluteFill, Audio, Sequence, Series, staticFile } from 'remotion';
import { GnaroSceneRendererV2 } from './GnaroOverlayV2';

export type GnaroSceneTypeV2 =
  | 'episode_title'
  | 'intertitle'
  | 'shock'
  | 'clip'
  | 'image'
  | 'logo'
  | 'diagram'
  | 'funnel'
  | 'flow'
  | 'compare'
  | 'counter'
  | 'task_before'
  | 'task_summary'
  | 'flash_cut'
  | 'task_after';

export interface GnaroSceneV2 {
  id: string;
  type: GnaroSceneTypeV2;
  episode?: string;
  title?: string;
  subtitle?: string;
  text?: string;
  emphasis?: string;
  clip_path?: string;
  image_path?: string;
  audio_path?: string;
  stage?: string;
  duration_sec: number;
  // funnel
  total?: number;
  selected?: number;
  unit?: string;
  // flow
  steps?: string[];
  // counter
  value?: number;
  // compare
  from?: string;
  to?: string;
  from_label?: string;
  to_label?: string;
  // task_before / task_summary
  label?: string;
  display?: string;
  // counter
  prefix?: string;
  theme?: string;
  // word-level timestamps from Whisper (generated by generate_tts.py)
  word_timestamps?: Array<{ word: string; start: number; end: number }>;
}

export interface GnaroVideoV2Props {
  scenes: GnaroSceneV2[];
  fps: number;
  audio_path?: string;
  audio_delay_sec?: number;
}

export const gnaroV2DefaultProps: GnaroVideoV2Props = {
  scenes: [],
  fps: 30,
};

const resolveClipSrc = (path: string): string =>
  path.startsWith('http') ? path : staticFile(path);

export const GnaroVideoV2: React.FC<GnaroVideoV2Props> = ({
  scenes,
  fps,
  audio_path,
  audio_delay_sec,
}) => {
  const audioDelayFrames = Math.round((audio_delay_sec ?? 0) * fps);
  return (
    <AbsoluteFill style={{ backgroundColor: '#0a0908' }}>
      {audio_path && (
        <Sequence from={audioDelayFrames}>
          <Audio src={resolveClipSrc(audio_path)} />
        </Sequence>
      )}
      <Series>
        {scenes.map((scene) => {
          const durationInFrames = Math.round(scene.duration_sec * fps);
          return (
            <Series.Sequence key={scene.id} durationInFrames={durationInFrames}>
              {scene.audio_path && (
                <Audio src={resolveClipSrc(scene.audio_path)} volume={(f) => Math.min(1, f / 2)} />
              )}
              <GnaroSceneRendererV2 scene={scene} durationInFrames={durationInFrames} />
            </Series.Sequence>
          );
        })}
      </Series>
    </AbsoluteFill>
  );
};
